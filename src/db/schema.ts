import { bigint, integer, pgTable, serial, text, timestamp } from 'drizzle-orm/pg-core';

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  uid: text('uid').notNull().unique(),
  email: text('email').notNull(),
  name: text('name').notNull().default('CRM User'),
  passwordHash: text('password_hash').notNull().default(''),
  role: text('role').notNull().default('Sales Agent'),
  agentId: text('agent_id').notNull().default(''),
  phone: text('phone').notNull().default(''),
  specialization: text('specialization').notNull().default('Real Estate Consultant'),
  accountStatus: text('account_status').notNull().default('Active'),
  createdAt: timestamp('created_at').defaultNow(),
});

